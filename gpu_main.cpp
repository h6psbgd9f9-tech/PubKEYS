#include "gpu_info.h"
#include "single_instance.h"
#include <iostream>
#include <vector>

// Байт видеопамяти на одну НИТЬ.
//
// Имя досталось от прежней оценки, а величина -- уже не оценка. gpu_plan
// считает keys_in_flight = blocks * threads_per_block, то есть «ключ в
// полёте» здесь означает нить; и расход нити -- это ровно сумма выделений в
// cuda_scan_init: d_work = 2*CUDA_HALF*32 байт, d_base = sizeof(cpt) = 72,
// d_basekey = 32.
//
// Прежние 256 занижали расход в 8 (CUDA_HALF=32) и в 32 раза (CUDA_HALF=128):
// советник печатал «85 МБ» там, где счёт занимает 2.7 ГБ. На карте с 4 ГБ
// человек по этому совету выбирал «на полную», а cuda_scan_init затем
// отказывал по нехватке памяти -- сразу после того, как советник сказал, что
// места вдоволь.
// cpt (две координаты по 32 байта плюс признак бесконечности) живёт в
// cuda_batch.cuh, а этот файл собирается и без nvcc -- поэтому 72 стоит
// числом с оговоркой, а не sizeof.
#include "cuda_scan.h"   // CUDA_HALF: одно число с ядром, а не второе такое же
static const size_t BYTES_PER_KEY = (size_t)CUDA_HALF * 32       // d_work
                                  + 72                            // d_base (cpt: 2*32 + выравнивание)
                                  + 32;                           // d_basekey

int gpu_advice_main() {
    std::cout << "\n============================================================\n"
              << "  Видеокарта и раскладка запуска\n"
              << "============================================================\n\n";

    std::vector<GpuInfo> gs;
    if (!gpu_detect(gs)) {
        std::cout << "  Видеокарты NVIDIA не найдено.\n\n"
                     "  Проверьте по порядку:\n"
                     "    nvidia-smi              — видит ли карту драйвер\n"
                     "    nvcc --version          — стоит ли CUDA Toolkit\n\n"
                     "  На Apple Silicon CUDA не бывает вовсе: там считает\n"
                     "  обычная версия программы на процессоре.\n";
        return 1;
    }

    for (const GpuInfo &g : gs) {
        std::cout << "  --- Карта " << g.index << " ---\n";
        gpu_print(g);

        // ТЕПЛО И ИЗНОС -- ЧЕСТНО, БЕЗ СТРАШИЛОК И БЕЗ БЕСПЕЧНОСТИ.
        //
        // Сжечь современную карту счётом нельзя: у неё аппаратная защита, она
        // сбросит частоты, а на пределе выключится сама. Пугать этим не надо.
        //
        // Изнашивается другое -- подшипники вентиляторов, термопаста, память
        // и цепи питания. Их старит не пик, а МЕСЯЦЫ работы под полной
        // нагрузкой. Рычаг здесь один и настоящий: предел мощности. На этой
        // задаче он почти не стоит скорости -- она упирается в арифметику, а
        // не в память, -- зато сильно снижает нагрев и шум.
        std::cout << "\n    Про нагрев: сжечь карту счётом нельзя — при перегреве\n"
                     "    она сбросит частоты, а на пределе выключится сама.\n"
                     "    Стареют вентиляторы, термопаста и питание, и стареют\n"
                     "    они от месяцев полной нагрузки, а не от одного прогона.\n";
        if (g.temp_slowdown)
            std::cout << "    Порог сброса частот: " << g.temp_slowdown << " C\n";
        if (g.power_limit_w)
            std::cout << "    Ограничить мощность: sudo nvidia-smi -i " << g.index
                      << " -pl <ватт>\n";
        std::cout << "    Смотреть вживую:     nvidia-smi -l 5\n";

        for (int L = LOAD_GENTLE; L <= LOAD_MAX; L++) {
            const GpuLoad load = (GpuLoad)L;
            gpu_print_plan(g, gpu_plan(g, load, BYTES_PER_KEY), load);
        }
        std::cout << "\n";
    }

    std::cout << "  Расход видеопамяти посчитан из оценки в "
              << BYTES_PER_KEY << " байт на ключ.\n"
                 "  Это ОЦЕНКА, а не замер: точное число будет известно, когда\n"
                 "  ядра будут написаны и измерены.\n";
    return 0;
}

