//  gpu_main.cpp — «какая карта и как её грузить», отдельной командой.
//
//  Запускается как  ./pkgpu  либо  ./pubkeyhunt --gpu
//
//  Смысл в том, чтобы это можно было посмотреть ДО начала счёта и без всякого
//  риска: команда ничего не запускает на карте, только спрашивает у неё
//  характеристики и печатает три раскладки на выбор.
