// ============================================================================
//  platform.h — единственное место, где программа знает про операционную
//               систему. Всё остальное написано так, будто система одна.
//
//  ЗАЧЕМ ЭТО ЗАВЕДЕНО.
//
//  До сих пор разница между системами жила россыпью: семнадцать #ifdef по
//  семи файлам. Пока систем было две и обе POSIX (macOS и Linux), это почти
//  не мешало — они отличались одной строкой в exe_dir и больше ничем.
//
//  Windows отличается в каждом из этих мест. Править россыпь — значит
//  наверняка про какое-то забыть, и забытое не упадёт при сборке: оно
//  соберётся и промолчит. Так уже случилось с run_capture в gpu_info.cpp:
//  под Windows там стояла заглушка, возвращавшая пустую строку, и опрос
//  видеокарты не работал бы ровно на той системе, ради которой всё затевалось.
//
//  Поэтому: одно место, один список, и каждая функция обязана иметь смысл на
//  всех трёх системах. Если на какой-то смысла нет — это пишется в комментарии
//  рядом, а не подразумевается.
//
//  ЧЕГО ЗДЕСЬ НЕТ. Обёрток «на всякий случай». Каждая функция ниже нужна хотя
//  бы одному месту в программе прямо сейчас.
// ============================================================================
#pragma once
#include <string>
#include <cstdio>   // FILE — для plat_fopen

// Как называется система, на которой собрано. Для сводки и отчётов об ошибках.
const char *plat_name();

// ------------------------------- пути ---------------------------------------
//
// Папка, в которой лежит САМА программа, а не та, откуда её запустили.
// Пустая строка — определить не удалось.
//
// Нужно затем, что база и настройки лежат рядом с программой: пользователь
// копирует два файла на другую машину и запускает двойным щелчком, а текущим
// каталогом при этом оказывается домашний.
std::string plat_exe_dir();

// Перейти в каталог. false — не вышло.
bool plat_chdir(const std::string &dir);

// ------------------------------ файлы ---------------------------------------
//
// Создать каталог, закрытый от посторонних пользователей машины.
// true — создан либо уже был.
//
// На Windows «закрытый от посторонних» означает другое, чем 0700: там права
// наследуются от родителя, и отдельного простого способа их сузить нет.
// Функция это НЕ скрывает: см. plat_privacy_note().
bool plat_make_dir_private(const std::string &path);

// Закрыть права на файл: только владелец, чтение и запись.
void plat_make_file_private(const std::string &path);

// Честно сказать, чего стоят закрытые права на этой системе. Программа
// печатает это при находке, потому что внутри лежат приватные ключи и человек
// должен знать, на что он опирается.
const char *plat_privacy_note();

// Сбросить файл на диск по-настоящему. Без этого запись остаётся в буферах
// системы, и при внезапном выключении чекпоинт окажется битым или пустым.
bool plat_fsync_file(const std::string &path);

// То же для каталога: на POSIX переименование файла становится долговечным
// только после сброса каталога. На Windows такого понятия нет — там функция
// возвращает true, ничего не делая, и это не упущение, а свойство системы.
bool plat_fsync_dir(const std::string &path);

// ----------------------------- консоль --------------------------------------
//
// Включить UTF-8 в консоли. Весь вывод программы кириллический; на Windows
// консоль по умолчанию в кодовой странице 866 или 1251, и текст выходит
// нечитаемым. Windows также отключает QuickEdit на время процесса, чтобы
// выделение текста мышью не замораживало вывод и рабочие потоки. Исходный
// режим ввода восстанавливается при обычном выходе. На POSIX ничего не надо.
void plat_console_utf8();

// ------------------------- питание ------------------------------------------
//
// Запретить автоматический сон и приостановку процесса на время поиска.
// Экран гаснет по таймеру Windows: DisplayRequired не запрашивается.
// on=false отпускает; при выходе из процесса система отпускает сама.
// false означает, что Windows не приняла запрос.
bool plat_keep_awake(bool on);

// Read-only external-power status. Unknown is not confirmation that AC returned.
// Windows reports adapter loss and a mains outage in the same way: on battery.
enum class PowerSource { unknown, mains, battery };
PowerSource plat_power_source();

// ------------------------- внешние команды ----------------------------------
//
// Запустить команду и НЕ ждать её. Отправка уведомления не должна
// задерживать поиск: находка уже записана на диск, а сеть может висеть
// минутами.
void plat_run_detached(const std::string &cmd);

// Запустить команду и забрать её вывод. Пустая строка — не вышло.
std::string plat_run_capture(const std::string &cmd);

// Есть ли такая программа в PATH.
bool plat_have_command(const std::string &name);

// Куда девать сообщения об ошибках внутри командной строки:
// «2>/dev/null» на POSIX, «2>NUL» на Windows.
const char *plat_devnull_2();

// Всё вместе -- и вывод, и ошибки -- в никуда. На Windows это ">NUL 2>&1",
// на POSIX ">/dev/null 2>&1". Путь /dev/null там просто не существует, и
// команда с ним падает с "The system cannot find the path specified".
const char *plat_devnull_all();

// Взять строку в кавычки, понятные оболочке ЭТОЙ системы.
//
// Разница не косметическая. sh снимает одинарные кавычки, cmd.exe -- нет: он
// передаёт их программе как есть, и curl получает URL вместе с апострофом,
// после чего отвергает его. Ровно из-за этого проверка Telegram сообщала
// "не доставлено" при совершенно исправном токене.
std::string plat_quote(const std::string &s);

// Перевести UTF-8 в кодировку, которую поймёт запускаемая программа, читающая
// аргументы как UTF-16 (то есть Java, а значит signal-cli). На POSIX ничего не
// делает. Подробности и оговорки -- у определения в platform.cpp.
//
// ВАЖНО: для curl этого делать НЕЛЬЗЯ -- ему UTF-8 доходит правильным сам, а
// после перевода он отправил бы в Telegram уже испорченный текст.
std::string plat_to_native(const std::string &utf8);

// Заменить файл path файлом tmp -- атомарно, поверх существующего.
//
// std::rename на POSIX это и делает; на Windows (MSVC CRT) он ОТКАЗЫВАЕТСЯ,
// если path уже существует, -- и чекпоинт обновлялся ровно один раз, первый,
// а дальше каждая запись тихо проваливалась. Здесь -- MoveFileEx с заменой.
bool plat_replace_file(const std::string &tmp, const std::string &path);

// Запустить команду и вернуть её код выхода (0 -- успех). Для программ,
// которые ничего не печатают на успех (signal-cli), это единственный способ
// понять, прошла ли отправка.
int plat_run_status(const std::string &cmd);

// Есть ли такой файл (обычный файл, не каталог).
bool plat_file_exists(const std::string &path);

// Имя переменной окружения так, как её раскрывает оболочка этой системы:
// "$NAME" в sh, "%NAME%" в cmd.
std::string plat_envref(const std::string &name);

// ПУТЬ В ВИДЕ, КОТОРЫЙ ПОНИМАЕТ СИСТЕМА.
//
// std::ifstream и std::ofstream на Windows принимают узкую строку и читают её
// в кодовой странице системы (CP1251), а пути внутри программы -- UTF-8.
// Кириллица в пути от этого превращается в мусор, и файл не находится. У MSVC
// есть нештатное расширение: у тех же потоков существует конструктор от
// широкой строки. plat_path_t и plat_wide() дают то, что ему нужно, и на
// POSIX не делают ничего -- там путь и так байты UTF-8.
//
//     std::ifstream f(plat_wide(path).c_str());
//
// Отдельный тип, а не всегда wstring: на POSIX широкой строки в путях нет
// вовсе, и притворяться, что есть, значило бы гонять преобразование впустую.
#ifdef _WIN32
typedef std::wstring plat_path_t;
#else
typedef std::string  plat_path_t;
#endif
plat_path_t plat_wide(const std::string &utf8);

// Открыть файл; путь в UTF-8. На Windows идёт через _wfopen (широкий API),
// поэтому путь с кириллицей открывается правильно независимо от кодовой
// страницы системы — обычный fopen читал бы те же байты как CP1251 и файл бы
// не нашёлся. На POSIX это обычный fopen. nullptr — открыть не удалось.
FILE *plat_fopen(const std::string &path, const char *mode);

// Удалить файл; путь в UTF-8. true — удалён. На Windows через _wremove по той
// же причине, что и plat_fopen.
bool plat_remove_file(const std::string &path);
