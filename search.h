// ============================================================================
//  search.h — SearchContext: всё изменяемое состояние одного поиска в одном
//  месте.
//
//  ЗАЧЕМ. Раньше состояние жило десятком отдельных глобальных переменных:
//  границы диапазона, счётчики, флаг остановки, позиция выдачи участков,
//  водяной знак завершённости, база целей, образец для блока ПРОВЕРКА. Пока
//  поиск в процессе один, это работает. Мешает оно в другом:
//
//    * проверку нельзя написать, не настроив предварительно половину
//      глобальных переменных и не вернув их потом обратно -- в самотесте
//      это видно, там всюду «сохранить, поменять, восстановить»;
//    * два поиска в одном процессе невозможны в принципе;
//    * рассуждать о потоках труднее: что именно они делят, приходится
//      искать по всему проекту.
//
//  ЧТО СДЕЛАНО И ЧЕГО НЕ СДЕЛАНО. В контекст ушло изменяемое состояние
//  поиска -- то, ради чего всё и затевалось. Конфигурация (g_cfg) осталась
//  глобальной сознательно: она читается, а не меняется, обращений к ней
//  почти три сотни, и перенос дал бы много правок при нулевой пользе.
//
//  Переходная мера: прежние имена (g_range_start, g_count и прочие) остались
//  как ССЫЛКИ на поля единственного экземпляра. Поэтому меню, уведомления и
//  прочий не переведённый код продолжают работать без изменений, а обход и
//  горячий цикл уже получают контекст явным доводом.
// ============================================================================
#pragma once

#include "common.h"
#include "traverse.h"
#include "targets.h"

#include <map>

struct SearchContext {
    // ---- границы и нарезка -------------------------------------------------
    u256    range_start{};
    u256    range_end{};
    uint8_t total_blocks256[32] = {};

    // ---- выдача участков ---------------------------------------------------
    ChunkCounter chunk_seq;

    // ---- учёт завершённости (водяной знак для чекпоинта) -------------------
    //
    // Ниже done_below закрыто всё; выше лежат номера, досчитанные раньше
    // своих младших соседей. Подробности -- у объявления chunk_done.
    std::mutex        mtx_done;
    ChunkIdx          done_below;
    // Actual primary candidates attached to completed ordinals. Empty slots
    // have weight zero; counts move only with the contiguous watermark.
    std::map<ChunkIdx, uint64_t> done_ahead;
    u256 confirmed_items{};
    bool confirmed_items_valid = true;

    // ---- счётчики и остановка ----------------------------------------------
    std::atomic<uint64_t> count{0};        // проверено ключей ЗА ЭТОТ ЗАПУСК

    // СДЕЛАНО ДО ЭТОГО ЗАПУСКА.
    //
    // count обнуляется при каждом старте, а чекпоинт копится между
    // запусками. Пока процент считался от одного count, после продолжения
    // он показывал долю ТЕКУЩЕГО сеанса, называя её «Пройдено»: программа
    // отработала до 25%, остановилась, продолжила -- и снова отчитывалась о
    // единицах процента. Не поломка счёта, а неверная подпись под верным
    // числом; хуже тем, что число выглядит осмысленным.
    //
    // Здесь -- сколько участков было закрыто до старта, в ключах (или в
    // кандидатах при маске). long double: номер участка 256-битный, точных
    // цифр для процента хватает с запасом.
    long double resumed_items = 0.0L;
    std::atomic<uint64_t> found_num{0};
    std::atomic<int>      zone_idx{-1};    // текущая зона, -1 -- неприменимо
    std::atomic<bool>     stop{false};

    // ---- образец для блока ПРОВЕРКА ----------------------------------------
    std::mutex mtx_sample;
    u256       sample_key{};
    bool       sample_valid = false;

    // ---- цели --------------------------------------------------------------
    PubDB db;

    SearchContext() { u256_zero(range_start); u256_zero(range_end); u256_zero(sample_key); }

    // Копировать нельзя: внутри мьютексы и атомики, да и смысла нет.
    SearchContext(const SearchContext &) = delete;
    SearchContext &operator=(const SearchContext &) = delete;

    // Сбросить счётчики и позицию, не трогая границы и базу. Нужно проверкам,
    // которые гоняют один и тот же контекст несколько раз подряд.
    void reset_progress() {
        count.store(0);
        resumed_items = 0.0L;
        found_num.store(0);
        zone_idx.store(-1);
        stop.store(false);
        chunk_seq.set(ChunkIdx{});
        std::lock_guard<std::mutex> lk(mtx_done);
        done_below = ChunkIdx{};
        done_ahead.clear();
        u256_zero(confirmed_items);
        confirmed_items_valid = true;
    }
};

// Единственный экземпляр боевого поиска. Проверки могут создавать свои.
extern SearchContext g_search;
