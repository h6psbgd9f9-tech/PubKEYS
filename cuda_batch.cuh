// ============================================================================
//  cuda_batch.cuh — симметричный пакет P±iG и пакетное обращение.
//
//  Сердце счёта. Как и поле, помечено __host__ __device__ и собирается
//  дважды: значит проверяется на процессоре сверкой с работающей версией.
//
//  ЧТО ЗДЕСЬ ПРОИСХОДИТ.
//
//  Нужны абсциссы точек P+1G, P+2G, ..., P+nG и P-1G, ..., P-nG. В лоб каждая
//  стоит одного обращения в поле, а обращение -- это 255 возведений в квадрат,
//  дороже всего остального вместе взятого.
//
//  Два приёма убирают эту цену почти полностью.
//
//  СИММЕТРИЯ. Точке -iG отвечает (x_i, -y_i): та же абсцисса, противоположная
//  ордината. Значит разность абсцисс x_i - x_P у P+iG и P-iG ОДНА И ТА ЖЕ, и
//  обращать её надо один раз на пару. Наклоны различаются знаком слагаемого в
//  числителе, а квадрат наклона знака не помнит -- поэтому обе абсциссы
//  получаются из одного обращения.
//
//  ПАКЕТНОЕ ОБРАЩЕНИЕ (приём Монтгомери). Вместо n обращений: перемножаем все
//  разности нарастающим итогом, обращаем ОДНО произведение, и раскручиваем
//  обратно, добывая каждое обращение тремя умножениями. Итого одно обращение
//  на весь пакет вместо n.
//
//  Отсюда стоимость около трёх умножений на ключ вместо двухсот пятидесяти.
// ============================================================================
#pragma once
#include <stddef.h>          // size_t: шаг раскладки, см. cpt_batch_visit
#include "cuda_field.cuh"

// Точка в аффинных координатах. Бесконечность отмечается отдельно: у неё нет
// координат вовсе, и притворяться, что есть, значит однажды посчитать по ним.
struct cpt {
    cfe x, y;
    int inf;
};

// --------------------------------------------------------------------------
//  ПАКЕТНОЕ ОБРАЩЕНИЕ n ЗНАЧЕНИЙ ЗА ОДНО.
//
//  scratch должен вмещать n элементов -- это нарастающие произведения.
//  Нулевых значений среди входных быть НЕ ДОЛЖНО: обращать нечего, и весь
//  пакет испортится молча. Вызывающий обязан отсеять вырожденный случай
//  заранее; здесь проверка стоила бы ветвления на каждый элемент.
// --------------------------------------------------------------------------
FD_HD FD_IN void cfe_inv_batch(cfe *out, const cfe *in, int n, cfe *scratch) {
    // Нарастающие произведения: scratch[i] = in[0]*in[1]*...*in[i]
    cfe_set(scratch[0], in[0]);
    for (int i = 1; i < n; i++) cfe_mul(scratch[i], scratch[i - 1], in[i]);

    // Одно настоящее обращение -- всего произведения.
    cfe acc;
    cfe_inv(acc, scratch[n - 1]);

    // Раскручиваем назад: три умножения на каждое обращение.
    for (int i = n - 1; i > 0; i--) {
        cfe_mul(out[i], acc, scratch[i - 1]);
        cfe_mul(acc, acc, in[i]);
    }
    cfe_set(out[0], acc);
}

// --------------------------------------------------------------------------
//  СИММЕТРИЧНЫЙ ПАКЕТ.
//
//  По центру P и таблице кратных gt[i] = (i+1)*Q считает абсциссы
//  P + (i+1)Q и P - (i+1)Q для всех i < half.
//
//  dx и iv -- рабочие массивы на half элементов каждый; их передаёт
//  вызывающий, потому что на видеокарте место под них выделяется заранее и
//  на всю жизнь ядра, а не на каждый вызов.
//
//  Возвращает 0, если пакет вырожден: среди разностей абсцисс оказался нуль,
//  то есть P совпал с +-(i+1)Q. Тогда абсциссы НЕ заполняются, и вызывающий
//  обязан разобрать этот пакет поштучно. Молча подставить единицу вместо нуля
//  -- ровно та ошибка, которая когда-то была в процессорной версии: формула
//  считалась по подставленному значению, и ключи этого пакета не проверялись
//  вовсе, без всякого признака.
// --------------------------------------------------------------------------
FD_HD FD_IN int cpt_batch_xs(const cpt &P, const cpt *gt, int half,
                             cfe *out_plus, cfe *out_minus,
                             cfe *dx, cfe *iv) {
    if (P.inf) return 0;

    for (int i = 0; i < half; i++) {
        cfe_sub(dx[i], gt[i].x, P.x);
        if (cfe_is_zero(dx[i])) return 0;      // вырожденный пакет
    }

    cfe_inv_batch(iv, dx, half, out_plus);     // out_plus временно как scratch

    for (int i = 0; i < half; i++) {
        cfe s, t, sq;

        // P + (i+1)Q: наклон (y_i - y_P) / (x_i - x_P)
        cfe_sub(t, gt[i].y, P.y);
        cfe_mul(s, t, iv[i]);
        cfe_sqr(sq, s);
        cfe_sub(sq, sq, P.x);
        cfe_sub(out_plus[i], sq, gt[i].x);

        // P - (i+1)Q: у -Q ордината противоположна, значит в числителе сумма.
        // Квадрат наклона знака не помнит -- та же разность абсцисс годится.
        cfe_add(t, gt[i].y, P.y);
        cfe_mul(s, t, iv[i]);
        cfe_sqr(sq, s);
        cfe_sub(sq, sq, P.x);
        cfe_sub(out_minus[i], sq, gt[i].x);
    }
    return 1;
}

// --------------------------------------------------------------------------
//  ОБРАЩЕНИЕ ПАКЕТА НА МЕСТЕ.
//
//  То же самое, что cfe_inv_batch, но результат ложится в тот же массив, из
//  которого взяты значения. Нужно ради памяти: см. cpt_batch_visit ниже.
//
//  Единственная тонкость -- строка `cfe cur`. В обратном ходе acc умножается
//  на ИСХОДНОЕ a[i], а строкой выше a[i] уже затёрт ответом. Без этой копии
//  обращения со второго элемента пошли бы неверными, причём молча: массив
//  заполнен, размер верный, значения мусорные.
// --------------------------------------------------------------------------
FD_HD FD_IN void cfe_inv_batch_inplace(cfe *a, int n, cfe *scratch) {
    cfe_set(scratch[0], a[0]);
    for (int i = 1; i < n; i++) cfe_mul(scratch[i], scratch[i - 1], a[i]);

    cfe acc;
    cfe_inv(acc, scratch[n - 1]);

    for (int i = n - 1; i > 0; i--) {
        cfe cur; cfe_set(cur, a[i]);           // a[i] сейчас будет затёрт
        cfe_mul(a[i], acc, scratch[i - 1]);
        cfe_mul(acc, acc, cur);
    }
    cfe_set(a[0], acc);
}

// --------------------------------------------------------------------------
//  ПАКЕТ, КОТОРЫЙ НИЧЕГО НЕ ЗАПОМИНАЕТ.
//
//  Считает те же самые SPAN = 2*half абсцисс, что и cpt_batch_xs, но не
//  складывает их в массивы, а СРАЗУ отдаёт каждую вызывающему: visit(off, x),
//  где off -- место ключа в пакете, 0..2*half-1, а центр стоит на off = half.
//
//  ЗАЧЕМ. cpt_batch_xs требует двух массивов на half элементов поля: out_plus
//  и out_minus. На видеокарте это локальная память нити, а локальная память
//  там -- та же глобальная, только приватная: при half = 128 выходит 8 КБ на
//  нить, которые ядро сперва целиком запишет, а потом целиком прочитает.
//  Проверка же нужна ровно один раз и сразу -- значение живёт мгновение.
//  Убрав оба массива, мы снимаем с каждой нити 8 КБ записи и 8 КБ чтения на
//  каждый пакет и освобождаем место под БОЛЬШИЙ пакет.
//
//  А больший пакет -- это меньше обращений на ключ, и в этом вся выгода. Одно
//  обращение в поле стоит около 271 умножения, и оно одно на весь пакет:
//  при half = 32 это 8.5 умножения на ключ, при half = 128 -- 2.1. Остальное
//  в пакете стоит примерно 7 умножений на ключ, так что разница ощутимая.
//
//  ПОЧЕМУ cpt_batch_xs ОСТАВЛЕН. По нему написаны проверки, сверяющие пакет с
//  честным k*G. Он остаётся образцом: cuda_field_test сверяет эту функцию с
//  ним значение в значение, и пока они совпадают, все прежние проверки
//  относятся и к ней.
//
//  Возвращает 0 на вырожденном пакете -- так же, как cpt_batch_xs, и по той
//  же причине: подставить единицу вместо нуля значит молча не проверить его
//  ключи.
// --------------------------------------------------------------------------
//  ПОЧЕМУ ЗДЕСЬ ОДИН МАССИВ И ПОЧЕМУ ОН С ШАГОМ.
//
//  Считает то же самое, что и раньше, и в том же порядке отдаёт значения. Две
//  вещи изменились, и обе -- про память, а не про математику.
//
//  1. ОДИН МАССИВ ВМЕСТО ДВУХ. Хранились и разности абсцисс dx, и результат их
//     обращения. Теперь хранится только цепочка произведений: на обратном ходе
//     разность восстанавливается одним вычитанием из gt, который лежит в общей
//     памяти и только читается. Вычитание в поле стоит несравнимо дешевле
//     чтения 32 байт из видеопамяти, а обращений к массиву стало втрое меньше.
//
//  2. ШАГ ВМЕСТО СПЛОШНОГО КУСКА. Вызывающий передаёт не «свой кусок», а базу
//     и шаг: запись i нити t лежит по адресу pref[i*stride + t]. Раньше у
//     каждой нити был сплошной кусок в 8 КБ, и соседние нити оказывались на
//     8 КБ друг от друга. Карта читает память строками по 128 байт: варп из 32
//     нитей брал из каждой строки по 32 байта и выбрасывал остальные 96 --
//     вчетверо больше трафика, чем нужно. С шагом варп забирает 32 подряд
//     идущих куска, укладывающихся в строки целиком.
//
//     Хостовые проверки передают stride = 1 и получают прежнюю сплошную
//     раскладку -- тот же код служит обоим.
//
//  Вместе это около восьмикратного сокращения обращений к видеопамяти на тот
//  же счёт. Замер на карте показал, что ядро упиралось именно в них: перевод
//  умножения на ассемблер дал всего 5 %, хотя арифметики в ядре сто процентов
//  работы -- значит ядро не считало, а ждало.
//
//  Возвращает 0 на вырожденном пакете -- как и прежде, и по той же причине:
//  подставить единицу вместо нуля значит молча не проверить его ключи.
//  Отказ происходит на прямом ходе, до первого visit, поэтому вызывающий
//  видит ровно то же поведение, что и раньше.
// --------------------------------------------------------------------------
template <class Visit>
FD_HD FD_IN int cpt_batch_visit(const cpt &P, const cpt *gt, int half,
                                cfe *pref, size_t stride, Visit &visit) {
    if (P.inf) return 0;

    // Прямой ход: pref[i] -- произведение разностей dx_0 .. dx_{i-1}.
    // Сама разность НЕ сохраняется: gt лежит в общей памяти и только читается,
    // поэтому на обратном ходе она восстанавливается одним вычитанием. Это и
    // есть отказ от второго массива.
    cfe acc; cfe_one(acc);
    for (int i = 0; i < half; i++) {
        cfe_set(pref[(size_t)i * stride], acc);
        cfe dx; cfe_sub(dx, gt[i].x, P.x);
        if (cfe_is_zero(dx)) return 0;         // вырожденный пакет
        cfe_mul(acc, acc, dx);
    }

    cfe inv_acc; cfe_inv(inv_acc, acc);

    visit(half, P.x);                          // центр пакета -- это сам P

    // Обратный ход. inv_acc на шаге i равен обращению произведения
    // dx_0..dx_i, поэтому inv_acc * pref[i] -- это ровно 1/dx_i.
    for (int i = half - 1; i >= 0; i--) {
        cfe dx; cfe_sub(dx, gt[i].x, P.x);
        cfe inv_dx; cfe_mul(inv_dx, inv_acc, pref[(size_t)i * stride]);
        cfe_mul(inv_acc, inv_acc, dx);

        cfe s, t, sq, x;

        // P + (i+1)Q -- ключ на half + i + 1
        cfe_sub(t, gt[i].y, P.y);
        cfe_mul(s, t, inv_dx);
        cfe_sqr(sq, s);
        cfe_sub(sq, sq, P.x);
        cfe_sub(x, sq, gt[i].x);
        // ВЕРХНИЙ КРАЙ ПРОПУСКАЕТСЯ: иначе пакет накрыл бы 2*half+1 ключей и
        // заехал на первый ключ следующей нити -- тот проверялся бы дважды.
        if (i + 1 < half) visit(half + i + 1, x);

        // P - (i+1)Q -- ключ на half - i - 1
        cfe_add(t, gt[i].y, P.y);
        cfe_mul(s, t, inv_dx);
        cfe_sqr(sq, s);
        cfe_sub(sq, sq, P.x);
        cfe_sub(x, sq, gt[i].x);
        visit(half - i - 1, x);
    }
    return 1;
}

template <class Visit>
FD_HD FD_IN int cpt_batch_visit_step(const cpt &P, const cpt *gt, int half,
                                cfe *pref, size_t stride, Visit &visit, const cpt &step, cpt &next, bool &advanced) {
    advanced = false;
    if (P.inf) return 0;

    // Прямой ход: pref[i] -- произведение разностей dx_0 .. dx_{i-1}.
    // Сама разность НЕ сохраняется: gt лежит в общей памяти и только читается,
    // поэтому на обратном ходе она восстанавливается одним вычитанием. Это и
    // есть отказ от второго массива.
    cfe acc; cfe_one(acc);
    for (int i = 0; i < half; i++) {
        cfe_set(pref[(size_t)i * stride], acc);
        cfe dx; cfe_sub(dx, gt[i].x, P.x);
        if (cfe_is_zero(dx)) return 0;         // вырожденный пакет
        cfe_mul(acc, acc, dx);
    }

    // Add the next-center denominator to the same Montgomery inversion.
    // Exceptional additions retain the original cpt_add path in the caller.
    cfe step_dx; cfe_zero(step_dx);
    if (!step.inf) cfe_sub(step_dx, step.x, P.x);
    const bool can_advance = !step.inf && !cfe_is_zero(step_dx);
    cfe inv_acc;
    if (can_advance) {
        cfe product, total_inverse, step_inverse;
        cfe_mul(product, acc, step_dx);
        cfe_inv(total_inverse, product);
        cfe_mul(step_inverse, total_inverse, acc);
        cfe_mul(inv_acc, total_inverse, step_dx);
        cfe slope, delta, sq, x, y;
        cfe_sub(delta, step.y, P.y);
        cfe_mul(slope, delta, step_inverse);
        cfe_sqr(sq, slope);
        cfe_sub(x, sq, P.x); cfe_sub(x, x, step.x);
        cfe_sub(delta, P.x, x);
        cfe_mul(y, slope, delta); cfe_sub(y, y, P.y);
        cfe_set(next.x, x); cfe_set(next.y, y); next.inf = 0;
        advanced = true;
    } else {
        cfe_inv(inv_acc, acc);
    }

    visit(half, P.x);                          // центр пакета -- это сам P

    // Обратный ход. inv_acc на шаге i равен обращению произведения
    // dx_0..dx_i, поэтому inv_acc * pref[i] -- это ровно 1/dx_i.
    for (int i = half - 1; i >= 0; i--) {
        cfe dx; cfe_sub(dx, gt[i].x, P.x);
        cfe inv_dx; cfe_mul(inv_dx, inv_acc, pref[(size_t)i * stride]);
        cfe_mul(inv_acc, inv_acc, dx);

        cfe s, t, sq, x;

        // P + (i+1)Q -- ключ на half + i + 1
        cfe_sub(t, gt[i].y, P.y);
        cfe_mul(s, t, inv_dx);
        cfe_sqr(sq, s);
        cfe_sub(sq, sq, P.x);
        cfe_sub(x, sq, gt[i].x);
        // ВЕРХНИЙ КРАЙ ПРОПУСКАЕТСЯ: иначе пакет накрыл бы 2*half+1 ключей и
        // заехал на первый ключ следующей нити -- тот проверялся бы дважды.
        if (i + 1 < half) visit(half + i + 1, x);

        // P - (i+1)Q -- ключ на half - i - 1
        cfe_add(t, gt[i].y, P.y);
        cfe_mul(s, t, inv_dx);
        cfe_sqr(sq, s);
        cfe_sub(sq, sq, P.x);
        cfe_sub(x, sq, gt[i].x);
        visit(half - i - 1, x);
    }
    return 1;
}

// --------------------------------------------------------------------------
//  СЛОЖЕНИЕ ТОЧЕК В АФФИННЫХ КООРДИНАТАХ.
//
//  Нужно только для сдвига базы пакета -- раз на весь пакет, поэтому одно
//  обращение здесь не жаль. В горячей части его нет.
// --------------------------------------------------------------------------
FD_HD FD_IN void cpt_add(cpt &r, const cpt &a, const cpt &b) {
    if (a.inf) { r = b; return; }
    if (b.inf) { r = a; return; }

    if (cfe_cmp(a.x, b.x) == 0) {
        cfe sum;
        cfe_add(sum, a.y, b.y);
        if (cfe_is_zero(sum)) { r.inf = 1; return; }   // b == -a

        // Удвоение: наклон 3x^2 / 2y  (у secp256k1 коэффициент a равен нулю)
        cfe x2, three_x2, two_y, inv, s, sq;
        cfe_sqr(x2, a.x);
        cfe_add(three_x2, x2, x2);
        cfe_add(three_x2, three_x2, x2);
        cfe_add(two_y, a.y, a.y);
        cfe_inv(inv, two_y);
        cfe_mul(s, three_x2, inv);
        cfe_sqr(sq, s);
        cfe_sub(sq, sq, a.x);
        cfe rx; cfe_sub(rx, sq, a.x);
        cfe d; cfe_sub(d, a.x, rx);
        cfe ry; cfe_mul(ry, s, d); cfe_sub(ry, ry, a.y);
        cfe_set(r.x, rx); cfe_set(r.y, ry); r.inf = 0;
        return;
    }

    cfe dx, dy, inv, s, sq;
    cfe_sub(dx, b.x, a.x);
    cfe_sub(dy, b.y, a.y);
    cfe_inv(inv, dx);
    cfe_mul(s, dy, inv);
    cfe_sqr(sq, s);
    cfe_sub(sq, sq, a.x);
    cfe rx; cfe_sub(rx, sq, b.x);
    cfe d; cfe_sub(d, a.x, rx);
    cfe ry; cfe_mul(ry, s, d); cfe_sub(ry, ry, a.y);
    cfe_set(r.x, rx); cfe_set(r.y, ry); r.inf = 0;
}
